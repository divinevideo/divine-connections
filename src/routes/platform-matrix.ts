/** The proof form posts the legacy `twitter` alias, which the verify API normalizes to `x`. */
export const PROOF_VALUE_OVERRIDES: Record<string, string> = { x: 'twitter' }

/** A platform's proof-post path is only usable when its secret is installed here. */
export function canProof(p: PlatformCapability, env: Env): boolean {
  return p.proofFormat !== null && (!p.proofRequiresSecret || Boolean(env[p.proofRequiresSecret]))
}

/** Rows for the API reference's platform table. */
export function platformTableRows(_env: Env): string {
  return PLATFORMS.map((p) => {
    const proofCell = p.proofFormat === null
      ? 'Not supported — connect the account instead'
      : p.proofRequiresSecret
        ? `${p.proofFormat} (needs <code>${p.proofRequiresSecret}</code>)`
        : p.proofFormat
    const connectCell = p.connect ? 'Yes' : (p.connectDeferred ?? 'No')
    return `        <tr><td><code>${p.key}</code></td><td>${p.identity}</td><td>${proofCell}</td><td>${connectCell}</td></tr>`
  }).join('\n')
}
